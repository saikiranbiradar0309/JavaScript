// Used to increase or descrease value of a variable by 1

let a = 10;

// 1. Increment operator (++)
// Increases the value of a variable by 1.
a++;
console.log(a); // 11

// 2. Decrement operator (--)
// Decreases the value of a variable by 1.
let b = 20;
b--;
console.log(b); // 19

// 3. Pre-increment operator (++a)
// Increases the value of a variable by 1 before using it in an expression.
let c = 5;
console.log(++c); // 6

// 4. Post-increment operator (a++)
// Increases the value of a variable by 1 after using it in an expression.
let d = 15;
console.log(d++); // 15
console.log(d);   // 16

// 5. Pre-decrement operator (--a)
// Decreases the value of a variable by 1 before using it in an expression.
let e = 8;
console.log(--e); // 7

// 6. Post-decrement operator (a--)
// Decreases the value of a variable by 1 after using it in an expression.
let f = 10;
f--;
console.log(f); // 9